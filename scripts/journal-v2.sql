-- ----------------------------------------------------------------------------
-- 7. close_entry function
-- ----------------------------------------------------------------------------
create or replace function public.close_entry(
  p_entry_id bigint,
  p_exit_price numeric,
  p_result_pl numeric,
  p_lesson text default null,
  p_thoughts text default null,
  p_emotion_after text default null,
  p_moods text[] default array[]::text[]
) returns bigint as $$
declare
  v_entry record;
  v_shot_count bigint;
  v_trade_id bigint;
  v_mood text;
begin
  -- 1. Fetch entry and verify ownership
  select * into v_entry
  from public.journal_entries
  where id = p_entry_id and user_id = auth.uid()
  for update;

  if not found then
    raise exception 'Journal entry % not found or not owned by current user.', p_entry_id;
  end if;

  if v_entry.status = 'closed' then
    raise exception 'Journal entry % is already closed.', p_entry_id;
  end if;

  -- 2. Verify minimum 2 screenshots
  select count(*) into v_shot_count
  from public.entry_shots
  where entry_id = p_entry_id;

  if v_shot_count < 2 then
    raise exception 'A manual trade cannot be closed without at least 2 screenshots (entry and exit). Currently has %.', v_shot_count;
  end if;

  -- 3. Insert row into trades
  insert into public.trades (
    user_id,
    pair,
    direction,
    entry_price,
    exit_price,
    size,
    setup_type,
    notes,
    profit_loss,
    log_method
  ) values (
    auth.uid(),
    v_entry.pair,
    v_entry.direction,
    coalesce(v_entry.planned_entry, 0),
    p_exit_price,
    coalesce(v_entry.size, 0),
    'untagged',
    coalesce(p_lesson, v_entry.reasons, ''),
    p_result_pl,
    'plan'
  ) returning id into v_trade_id;

  -- 4. Update journal_entries
  update public.journal_entries set
    trade_id = v_trade_id,
    status = 'closed',
    exit_price = p_exit_price,
    result_pl = p_result_pl,
    lesson = p_lesson,
    thoughts = p_thoughts,
    emotion_after = p_emotion_after,
    closed_at = now()
  where id = p_entry_id;

  -- 5. Copy screenshots' trade_id
  update public.entry_shots set
    trade_id = v_trade_id
  where entry_id = p_entry_id and trade_id is null;

  -- 6. Insert moods
  if p_moods is not null then
    foreach v_mood in array p_moods loop
      v_mood := lower(trim(v_mood));
      if v_mood in ('calm', 'anxious', 'confident', 'frustrated', 'impatient') then
        insert into public.moods (trade_id, mood_tag)
        values (v_trade_id, v_mood);
      end if;
    end loop;
  end if;

  return v_trade_id;
end;
$$ language plpgsql security definer set search_path = public;
