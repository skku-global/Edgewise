-- ----------------------------------------------------------------------------
-- 2. Replace trigger lock_closed_entries
-- Locked: pair, direction, planned_entry, stop_loss, take_profit, size, exit_price, result_pl, reasons, status
-- Editable: lesson, thoughts, emotion_after, feelings_after, review, checkins, grade, rules_result, flags, ai_summary
-- ----------------------------------------------------------------------------
create or replace function public.lock_closed_entries() returns trigger as $$
begin
  if old.status = 'closed' then
    if (new.pair is distinct from old.pair) or
       (new.direction is distinct from old.direction) or
       (new.planned_entry is distinct from old.planned_entry) or
       (new.stop_loss is distinct from old.stop_loss) or
       (new.take_profit is distinct from old.take_profit) or
       (new.size is distinct from old.size) or
       (new.exit_price is distinct from old.exit_price) or
       (new.result_pl is distinct from old.result_pl) or
       (new.reasons is distinct from old.reasons) or
       (new.status is distinct from old.status) then
      raise exception 'This trade is closed and its core parameters cannot be edited.';
    end if;
  end if;
  return new;
end;
$$ language plpgsql;

drop trigger if exists lock_closed_entries on public.journal_entries;
create trigger lock_closed_entries
  before update on public.journal_entries
  for each row execute function public.lock_closed_entries();

