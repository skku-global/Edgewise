-- Safe user_id backfill
do $$
declare
  user_count   bigint;
  orphan_count bigint;
  only_user    uuid;
begin
  select count(*) into user_count from auth.users;
  select count(*) into orphan_count from public.journal_entries where user_id is null;

  if orphan_count = 0 then
    raise notice 'No unowned journal entries to backfill.';
  elsif user_count = 1 then
    select id into only_user from auth.users limit 1;
    update public.journal_entries set user_id = only_user where user_id is null;
    raise notice 'Backfilled % journal entries to the single account (%).', orphan_count, only_user;
  elsif user_count = 0 then
    raise notice 'No auth.users exist yet; keeping user_id nullable for now.';
  else
    raise notice 'Found % unowned entries across % accounts; assign manually if needed.', orphan_count, user_count;
  end if;
end $$;

