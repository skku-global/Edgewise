-- 3. entry_shots table & max 5 constraint
-- ----------------------------------------------------------------------------
create table if not exists public.entry_shots (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  entry_id bigint references public.journal_entries(id) on delete cascade,
  trade_id bigint references public.trades(id) on delete cascade,
  phase text not null check (phase in ('before', 'during', 'after')),
  path text not null,
  bytes int not null default 0,
  ai_read jsonb,
  content_hash text,
  created_at timestamptz not null default now(),
  constraint entry_or_trade_set check (entry_id is not null or trade_id is not null)
);

create or replace function public.check_entry_shots_limit() returns trigger as $$
declare
  cnt bigint;
begin
  if new.entry_id is not null then
    select count(*) into cnt from public.entry_shots
    where entry_id = new.entry_id and id <> coalesce(new.id, -1);
    if cnt >= 5 then
      raise exception 'Cannot add more than 5 screenshots to a journal entry.';
    end if;
  end if;

  if new.trade_id is not null then
    select count(*) into cnt from public.entry_shots
    where trade_id = new.trade_id and id <> coalesce(new.id, -1);
    if cnt >= 5 then
      raise exception 'Cannot add more than 5 screenshots to a trade.';
    end if;
  end if;

  return new;
end;
$$ language plpgsql;

drop trigger if exists enforce_entry_shots_limit on public.entry_shots;
create trigger enforce_entry_shots_limit
  before insert or update on public.entry_shots
  for each row execute function public.check_entry_shots_limit();

